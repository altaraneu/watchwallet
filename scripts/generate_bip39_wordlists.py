#!/usr/bin/env python3
"""Generates core/security/.../Bip39Wordlists.kt from the official BIP-39 word lists.

Usage: python scripts/generate_bip39_wordlists.py <directory with english.txt, czech.txt...>

The lists come from https://github.com/bitcoin/bips/tree/master/bip-0039 (MIT, see NOTICE.md).
They are stored in the folded form that `SecretText.foldWord` produces: lower case, composed
Hangul and kana, Latin letters without diacritics. A JVM test checks that the two agree.
"""

from __future__ import annotations

import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / "core/security/src/commonMain/kotlin/com/altaran/watchwallet/core/security/Bip39Wordlists.kt"
LANGUAGES = [
    "english",
    "japanese",
    "korean",
    "spanish",
    "chinese_simplified",
    "chinese_traditional",
    "french",
    "italian",
    "czech",
    "portuguese",
]
WORDS = 2048
LINE = 100


def fold(word: str) -> str:
    result = []
    for char in unicodedata.normalize("NFC", word).lower():
        if ord(char) < 0x250:
            char = "".join(c for c in unicodedata.normalize("NFD", char) if not unicodedata.combining(c))
        result.append(char)
    return "".join(result)


def constant(language: str, words: list[str]) -> str:
    lines: list[str] = []
    current = ""
    for word in words:
        # Width is measured in characters: wide scripts simply give shorter lines on screen.
        if current and len(current) + len(word) + 1 > LINE:
            lines.append(current + " ")
            current = word
        else:
            current = f"{current} {word}" if current else word
    lines.append(current)
    # The indentation ktlint asks for: continuation lines one level deeper than the first.
    body = " +\n        ".join(f'"{line}"' for line in lines)
    return f"private const val {language.upper()} =\n    {body}\n"


def main() -> None:
    source = Path(sys.argv[1])
    constants = []
    for language in LANGUAGES:
        words = (source / f"{language}.txt").read_text("utf-8").split()
        if len(words) != WORDS:
            raise SystemExit(f"{language}: expected {WORDS} words, found {len(words)}")
        constants.append(constant(language, [fold(word) for word in words]))
    names = ", ".join(language.upper() for language in LANGUAGES)
    TARGET.write_text(
        "package com.altaran.watchwallet.core.security\n\n"
        "// Generated by scripts/generate_bip39_wordlists.py from the official BIP-39 lists. Do not edit.\n\n"
        + "\n".join(constants)
        + f"\n/** All official BIP-39 lists, space separated, in the folded form of `SecretText.foldWord`. */\n"
        + f"internal val BIP39_LISTS: List<String> = listOf({names})\n",
        "utf-8",
        newline="\n",
    )


if __name__ == "__main__":
    main()
